DROP VIEW IF EXISTS public.vw_live_pipeline_slo_current;
CREATE OR REPLACE VIEW public.vw_live_pipeline_slo_current AS
WITH cfg AS (
  SELECT
    COALESCE(
      (SELECT window_minutes
       FROM public.live_pipeline_slo_config
       WHERE is_active = true
       ORDER BY updated_at DESC, id DESC
       LIMIT 1),
      240
    )::INTEGER AS window_minutes,
    COALESCE(
      (SELECT min_snapshot_coverage_pct
       FROM public.live_pipeline_slo_config
       WHERE is_active = true
       ORDER BY updated_at DESC, id DESC
       LIMIT 1),
      100
    )::NUMERIC AS min_snapshot_coverage_pct,
    COALESCE(
      (SELECT min_state_coverage_pct
       FROM public.live_pipeline_slo_config
       WHERE is_active = true
       ORDER BY updated_at DESC, id DESC
       LIMIT 1),
      100
    )::NUMERIC AS min_state_coverage_pct,
    COALESCE(
      (SELECT min_pbp_coverage_pct
       FROM public.live_pipeline_slo_config
       WHERE is_active = true
       ORDER BY updated_at DESC, id DESC
       LIMIT 1),
      100
    )::NUMERIC AS min_pbp_coverage_pct,
    COALESCE(
      (SELECT max_missing_games
       FROM public.live_pipeline_slo_config
       WHERE is_active = true
       ORDER BY updated_at DESC, id DESC
       LIMIT 1),
      0
    )::INTEGER AS max_missing_games,
    COALESCE(
      (SELECT max_stale_games
       FROM public.live_pipeline_slo_config
       WHERE is_active = true
       ORDER BY updated_at DESC, id DESC
       LIMIT 1),
      0
    )::INTEGER AS max_stale_games
),
freshness AS (
  SELECT
    COALESCE(
      (SELECT snapshot_stale_seconds
       FROM public.live_pipeline_config
       WHERE is_active = true
       ORDER BY updated_at DESC, id DESC
       LIMIT 1),
      90
    )::INTEGER AS snapshot_stale_seconds,
    COALESCE(
      (SELECT pbp_stale_seconds
       FROM public.live_pipeline_config
       WHERE is_active = true
       ORDER BY updated_at DESC, id DESC
       LIMIT 1),
      60
    )::INTEGER AS pbp_stale_seconds
),
caps AS (
  SELECT
    c.league_id,
    c.sport,
    c.live_odds_supported,
    c.live_state_supported,
    c.pbp_supported,
    c.auto_recovery_enabled,
    c.slo_enforced
  FROM public.live_pipeline_capabilities c
  WHERE c.is_active = true
),
windowed AS (
  SELECT
    c.league_id,
    c.sport,
    c.live_odds_supported,
    c.live_state_supported,
    c.pbp_supported,
    c.auto_recovery_enabled,
    c.slo_enforced,
    v.match_id,
    v.game_phase,
    v.started,
    v.has_live_odds_snapshot,
    v.has_live_state,
    v.has_pbp,
    v.stale_seconds_snapshot,
    v.stale_seconds_pbp
  FROM caps c
  CROSS JOIN cfg
  LEFT JOIN public.vw_live_pipeline_coverage v
    ON v.league_id = c.league_id
   AND v.sport = c.sport
   AND v.started = true
   AND v.start_time >= now() - make_interval(mins => cfg.window_minutes)
),
agg AS (
  SELECT
    w.sport,
    w.league_id,
    BOOL_OR(w.live_odds_supported) AS live_odds_supported,
    BOOL_OR(w.live_state_supported) AS live_state_supported,
    BOOL_OR(w.pbp_supported) AS pbp_supported,
    BOOL_OR(w.auto_recovery_enabled) AS auto_recovery_enabled,
    BOOL_OR(w.slo_enforced) AS slo_enforced,
    COUNT(w.match_id)::INTEGER AS started_games,
    COUNT(w.match_id) FILTER (WHERE w.live_odds_supported)::INTEGER AS required_snapshot_games,
    COUNT(w.match_id) FILTER (WHERE w.live_odds_supported AND w.has_live_odds_snapshot)::INTEGER AS covered_snapshot_games,
    COUNT(w.match_id) FILTER (WHERE w.live_state_supported)::INTEGER AS required_state_games,
    COUNT(w.match_id) FILTER (WHERE w.live_state_supported AND w.has_live_state)::INTEGER AS covered_state_games,
    COUNT(w.match_id) FILTER (WHERE w.pbp_supported)::INTEGER AS required_pbp_games,
    COUNT(w.match_id) FILTER (WHERE w.pbp_supported AND w.has_pbp)::INTEGER AS covered_pbp_games,
    COUNT(w.match_id) FILTER (
      WHERE (w.live_odds_supported AND NOT COALESCE(w.has_live_odds_snapshot, false))
         OR (w.live_state_supported AND NOT COALESCE(w.has_live_state, false))
         OR (w.pbp_supported AND NOT COALESCE(w.has_pbp, false))
    )::INTEGER AS missing_required_games,
    COUNT(w.match_id) FILTER (
      WHERE w.game_phase = 'IN_PROGRESS'
        AND (
          (w.live_odds_supported AND COALESCE(w.stale_seconds_snapshot, 0) > f.snapshot_stale_seconds)
          OR (w.pbp_supported AND COALESCE(w.stale_seconds_pbp, 0) > f.pbp_stale_seconds)
        )
    )::INTEGER AS stale_required_games
  FROM windowed w
  CROSS JOIN freshness f
  GROUP BY w.sport, w.league_id
),
final AS (
  SELECT
    a.*,
    CASE
      WHEN a.required_snapshot_games > 0
        THEN ROUND((100.0 * a.covered_snapshot_games::NUMERIC / a.required_snapshot_games::NUMERIC), 2)
      ELSE 100.0
    END AS snapshot_coverage_pct,
    CASE
      WHEN a.required_state_games > 0
        THEN ROUND((100.0 * a.covered_state_games::NUMERIC / a.required_state_games::NUMERIC), 2)
      ELSE 100.0
    END AS state_coverage_pct,
    CASE
      WHEN a.required_pbp_games > 0
        THEN ROUND((100.0 * a.covered_pbp_games::NUMERIC / a.required_pbp_games::NUMERIC), 2)
      ELSE 100.0
    END AS pbp_coverage_pct
  FROM agg a
)
SELECT
  f.sport,
  f.league_id,
  cfg.window_minutes,
  f.live_odds_supported,
  f.live_state_supported,
  f.pbp_supported,
  f.auto_recovery_enabled,
  f.slo_enforced,
  f.started_games,
  f.required_snapshot_games,
  f.covered_snapshot_games,
  f.required_state_games,
  f.covered_state_games,
  f.required_pbp_games,
  f.covered_pbp_games,
  f.missing_required_games,
  f.stale_required_games,
  f.snapshot_coverage_pct,
  f.state_coverage_pct,
  f.pbp_coverage_pct,
  cfg.min_snapshot_coverage_pct,
  cfg.min_state_coverage_pct,
  cfg.min_pbp_coverage_pct,
  cfg.max_missing_games,
  cfg.max_stale_games,
  ARRAY_REMOVE(
    ARRAY[
      CASE WHEN f.snapshot_coverage_pct < cfg.min_snapshot_coverage_pct THEN 'SNAPSHOT_COVERAGE' END,
      CASE WHEN f.state_coverage_pct < cfg.min_state_coverage_pct THEN 'STATE_COVERAGE' END,
      CASE WHEN f.pbp_coverage_pct < cfg.min_pbp_coverage_pct THEN 'PBP_COVERAGE' END,
      CASE WHEN f.missing_required_games > cfg.max_missing_games THEN 'MISSING_REQUIRED' END,
      CASE WHEN f.stale_required_games > cfg.max_stale_games THEN 'STALE_REQUIRED' END
    ],
    NULL
  )::TEXT[] AS breach_reasons,
  (
    f.slo_enforced
    AND (
      f.snapshot_coverage_pct < cfg.min_snapshot_coverage_pct
      OR f.state_coverage_pct < cfg.min_state_coverage_pct
      OR f.pbp_coverage_pct < cfg.min_pbp_coverage_pct
      OR f.missing_required_games > cfg.max_missing_games
      OR f.stale_required_games > cfg.max_stale_games
    )
  ) AS slo_breach
FROM final f
CROSS JOIN cfg;

GRANT SELECT ON public.live_pipeline_capabilities TO anon, authenticated, service_role;
GRANT SELECT ON public.live_pipeline_slo_config TO anon, authenticated, service_role;
GRANT SELECT ON public.vw_live_pipeline_slo_current TO anon, authenticated, service_role;
