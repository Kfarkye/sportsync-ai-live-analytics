-- Live pipeline capability matrix + current SLO surface.
-- Purpose: make per-league expectations explicit (including PBP support),
-- then expose league-level SLO breach status in SQL for operational guardrails.

CREATE TABLE IF NOT EXISTS public.live_pipeline_capabilities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id TEXT NOT NULL UNIQUE,
  sport TEXT NOT NULL,
  live_odds_supported BOOLEAN NOT NULL DEFAULT true,
  live_state_supported BOOLEAN NOT NULL DEFAULT true,
  pbp_supported BOOLEAN NOT NULL DEFAULT true,
  auto_recovery_enabled BOOLEAN NOT NULL DEFAULT true,
  slo_enforced BOOLEAN NOT NULL DEFAULT true,
  is_active BOOLEAN NOT NULL DEFAULT true,
  notes TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_live_pipeline_capabilities_active
  ON public.live_pipeline_capabilities (is_active, sport, league_id);

