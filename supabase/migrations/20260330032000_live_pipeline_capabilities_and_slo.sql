CREATE TABLE IF NOT EXISTS public.live_pipeline_slo_config (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  is_active BOOLEAN NOT NULL DEFAULT true,
  window_minutes INTEGER NOT NULL DEFAULT 240 CHECK (window_minutes > 0),
  min_snapshot_coverage_pct NUMERIC(5,2) NOT NULL DEFAULT 100 CHECK (min_snapshot_coverage_pct >= 0 AND min_snapshot_coverage_pct <= 100),
  min_state_coverage_pct NUMERIC(5,2) NOT NULL DEFAULT 100 CHECK (min_state_coverage_pct >= 0 AND min_state_coverage_pct <= 100),
  min_pbp_coverage_pct NUMERIC(5,2) NOT NULL DEFAULT 100 CHECK (min_pbp_coverage_pct >= 0 AND min_pbp_coverage_pct <= 100),
  max_missing_games INTEGER NOT NULL DEFAULT 0 CHECK (max_missing_games >= 0),
  max_stale_games INTEGER NOT NULL DEFAULT 0 CHECK (max_stale_games >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_live_pipeline_slo_config_active
  ON public.live_pipeline_slo_config ((is_active))
  WHERE is_active;

